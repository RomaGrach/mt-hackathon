export function validateDesign002(c) {
  const errors = [];
  for (const p of Object.values(c.problems || {})) {
    if (!p.choices?.length || p.worst?.points !== 0 || !(p.ttl > 0))
      errors.push('Invalid problem ' + p.id);
    for (const o of [
      p.worst,
      ...p.choices,
      ...Object.values(p.dialogue || {}).flatMap((d) => d.choices),
    ]) {
      if (![0, 1, 2].includes(o.points) && !(o.points === null && p.dialogue?.[o.dialogue]))
        errors.push('Invalid outcome ' + p.id);
      if (o.next && !c.problems[o.next]) errors.push('Missing next ' + o.next);
      if ((o.tasks || []).some((id) => !c.tasks[id])) errors.push('Missing task ' + p.id);
      if ((o.safety || 0) > 0) errors.push('Problem cannot farm safety ' + p.id);
    }
  }
  for (const t of Object.values(c.tasks || {})) {
    if ((t.success.safety || 0) > 0 && !t.preventive) errors.push('Safety task must be preventive');
    if (t.risk && !c.problems[t.risk]) errors.push('Missing risk');
  }
  for (const v of Object.values(c.variants || {})) {
    if (
      !Number.isInteger(v.turns) ||
      v.turns < 1 ||
      Object.values(v.quotas).reduce((a, b) => a + b, 0) + 2 <= v.turns
    )
      errors.push('Insufficient work ' + v.id);
  }
  return errors;
}
